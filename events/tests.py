def test_event_source_unique_per_organization(db, organization):
    from django.db import IntegrityError, transaction

    EventSource.objects.create(organization=organization, url="https://x")
    # Isolate the constraint violation in its own atomic block so the broken
    # inner transaction is rolled back without poisoning the test's outer one.
    with pytest.raises(IntegrityError):
        with transaction.atomic():
            EventSource.objects.create(organization=organization, url="https://x")
    # A different org may reuse the same URL.
    other = Organization.objects.create(name="Other Org")
    EventSource.objects.create(organization=other, url="https://x")


def test_event_source_due_returns_only_approved_active_due(db, organization):
    from datetime import timedelta

    approved_due = EventSource.objects.create(
        organization=organization, url="https://1", is_approved=True
    )  # never fetched → due
    approved_soon = EventSource.objects.create(
        organization=organization, url="https://2", is_approved=True,
        next_due_at=timezone.now() + timedelta(hours=1),
    )  # not due yet
    approved_overdue = EventSource.objects.create(
        organization=organization, url="https://3", is_approved=True,
        next_due_at=timezone.now() - timedelta(hours=1),
    )  # due
    unapproved = EventSource.objects.create(
        organization=organization, url="https://4", is_approved=False
    )  # not approved
    paused = EventSource.objects.create(
        organization=organization, url="https://5", is_approved=True, is_active=False
    )  # paused

    due = set(EventSource.due().values_list("id", flat=True))
    assert due == {approved_due.id, approved_overdue.id}
    assert approved_soon.id not in due
    assert unapproved.id not in due
    assert paused.id not in due



def test_create_event_with_lat_lon_stores_location(db, authed_client):
    payload = {
        "title": "Berlin Meetup",
        "starts_at": timezone.now().isoformat(),
        "latitude": 52.52,
        "longitude": 13.405,
    }
    response = authed_client.post("/api/events/", payload, format="json")
    assert response.status_code == 201
    event = Event.objects.get(title="Berlin Meetup")
    assert event.location is not None
    assert round(event.location.y, 3) == 52.52  # latitude
    assert round(event.location.x, 3) == 13.405  # longitude
    # Echoed in the response.
    assert response.data["latitude"] == 52.52


def test_proximity_returns_nearby_events_only(db, api_client):
    # Berlin centre ~52.52, 13.405 ; Potsdam ~52.39, 13.06 (≈30 km away).
    Event.objects.create(
        title="Berlin PyNight",
        starts_at=timezone.now(),
        location="POINT(13.405 52.52)",
    )
    Event.objects.create(
        title="Potsdam Meetup",
        starts_at=timezone.now(),
        location="POINT(13.06 52.39)",
    )
    response = api_client.get(
        "/api/events/?lat=52.52&lon=13.405&radius_km=10", format="json"
    )
    assert response.status_code == 200
    results = response.data["results"] if "results" in response.data else response.data
    titles = {item["title"] for item in results}
    assert titles == {"Berlin PyNight"}


def test_proximity_annotates_distance_and_orders_nearest(db, api_client):
    Event.objects.create(
        title="Near",
        starts_at=timezone.now(),
        location="POINT(13.41 52.52)",
    )
    Event.objects.create(
        title="Far",
        starts_at=timezone.now(),
        location="POINT(13.50 52.55)",
    )
    response = api_client.get(
        "/api/events/?lat=52.52&lon=13.405&radius_km=100", format="json"
    )
    assert response.status_code == 200
    results = response.data["results"] if "results" in response.data else response.data
    assert [item["title"] for item in results] == ["Near", "Far"]
    assert results[0]["distance"] < results[1]["distance"]
    assert results[0]["distance"] is not None



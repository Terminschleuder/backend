def test_owner_can_update_and_delete_own_event(db, authed_client, user):
    event = Event.objects.create(title="Mine", starts_at=timezone.now(), created_by=user)
    response = authed_client.patch(
        f"/api/events/{event.id}/", {"title": "Updated"}, format="json"
    )
    assert response.status_code == 200
    assert response.data["title"] == "Updated"
    response = authed_client.delete(f"/api/events/{event.id}/")
    assert response.status_code == 204



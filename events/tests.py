def _png_bytes():
    """A tiny valid PNG (built with Pillow, the ImageField dependency)."""
    from io import BytesIO

    from PIL import Image

    buf = BytesIO()
    Image.new("RGB", (10, 10), (255, 0, 0)).save(buf, format="PNG")
    return buf.getvalue()


def test_event_with_hero_image_serializes_to_url(db, api_client, settings, tmp_path):
    from django.core.files.uploadedfile import SimpleUploadedFile

    # Keep test media out of the real MEDIA_ROOT.
    settings.MEDIA_ROOT = str(tmp_path)
    event = Event.objects.create(title="Hero Event", starts_at=timezone.now())
    event.hero_image.save(
        "hero.png",
        SimpleUploadedFile("hero.png", _png_bytes(), content_type="image/png"),
        save=False,
    )
    event.save(update_fields=["hero_image"])

    response = api_client.get(f"/api/events/{event.id}/", format="json")
    assert response.status_code == 200
    # Read-only absolute URL is exposed (uploads happen in the backoffice).
    assert response.data["hero_image"] is not None
    assert response.data["hero_image"].endswith("hero.png")



def test_service_account_needs_add_perm_to_create(db, api_client, user, editors_group):
    from django.contrib.auth import get_user_model
    from django.contrib.auth.models import Permission

    User = get_user_model()

    user.is_service_account = True
    user.save()
    api_client.force_authenticate(user=user)

    payload = {"title": "SA Event", "starts_at": timezone.now().isoformat()}
    # No add_event permission yet → 403.
    assert api_client.post("/api/events/", payload, format="json").status_code == 403

    # Grant add_event via the group → 201.
    perm = Permission.objects.get(codename="add_event", content_type__app_label="events")
    editors_group.permissions.add(perm)
    user.groups.add(editors_group)
    # Refetch the user: the first request cached the negative has_perm() result
    # on the in-memory instance. A fresh fetch (as the auth backend would give
    # on a real second request) picks up the newly granted group permission.
    user = User.objects.get(pk=user.pk)
    api_client.force_authenticate(user=user)
    assert api_client.post("/api/events/", payload, format="json").status_code == 201
def test_lifecycle_publish_action_sets_published_at(db, authed_client, user):
    from django.contrib.auth.models import Permission

    user.user_permissions.add(
        Permission.objects.get(content_type__app_label="events", codename="change_event")
    )
    from django.contrib.auth import get_user_model

    user = get_user_model().objects.get(pk=user.pk)
    authed_client.force_authenticate(user=user)

    event = Event.objects.create(
        title="Draft", starts_at=timezone.now(),
        created_by=user, status=Event.Status.DRAFT,
    )
    response = authed_client.post(f"/api/events/{event.id}/publish/")
    assert response.status_code == 200
    event.refresh_from_db()
    assert event.status == Event.Status.PUBLISHED
    assert event.published_at is not None

    # Cancel → archived lifecycle also reachable.
    cancel = authed_client.post(f"/api/events/{event.id}/cancel/")
    assert cancel.status_code == 200
    event.refresh_from_db()
    assert event.status == Event.Status.CANCELLED
    assert event.cancelled_at is not None


